def chn_to_code(chn_name: str, mapping: dict) -> str:
    """中文名转代码"""
    if chn_name in mapping:
        return mapping[chn_name]
    # try partial match
    for cn, code in mapping.items():
        if cn in chn_name or chn_name in cn:
            return code
    print(f"  ⚠️ 未找到映射: {chn_name}")
    return chn_name


def make_matches(data, mapping):
    """生成matches列表"""
    matches = []
    for row in data:
        home, away, hg, ag = row
        hc = chn_to_code(home, mapping)
        ac = chn_to_code(away, mapping)
        matches.append({"home": hc, "away": ac, "hg": hg, "ag": ag})
    return matches


def save_results(league, matches):
    """保存results.json"""
    path = os.path.join(BASE, "data", "live", league, "results.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"matches": matches}, f, ensure_ascii=False, indent=2)
    print(f"  ✅ {league}: {len(matches)} 场比赛已写入")


def run_elo(league):
    """运行elo_updater"""
    print(f"\n>>> 运行 elo_updater {league}...")
    result = subprocess.run(
        [sys.executable, os.path.join(BASE, "scripts", "elo_updater.py"), league, "--reset"],
        capture_output=True, text=True, encoding="utf-8",
        cwd=BASE
    )
    # Print last 20 lines of output
    lines = result.stdout.strip().split("\n")
    for line in lines[-15:]:
        print(f"  {line}")
    if result.returncode != 0:
        print(f"  ❌ 错误: {result.stderr[-500:]}")


